export function simulateSpots(n: number): Spot[] {
  const totalW = CITIES.reduce((s, c) => s + c[2], 0);
  const gauss = () => {
    // Box-Muller
    const u = Math.max(1e-9, Math.random());
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * Math.random());
  };
  const arr: Spot[] = [];
  for (let i = 0; i < Math.min(n, 50000); i++) {
    let sigma: number, anchor: [number, number];
    if (Math.random() < 0.3) {
      // 3割は世界の田舎へ(広めに散らす)
      const ru = RURAL[Math.floor(Math.random() * RURAL.length)];
      anchor = [ru[0], ru[1]];
      sigma = ru[2];
    } else {
      // 7割は都市圏(人口の重みで選ぶ)
      let r = Math.random() * totalW;
      let city = CITIES[0];
      for (const c of CITIES) { r -= c[2]; if (r <= 0) { city = c; break; } }
      anchor = [city[0], city[1]];
      sigma = 0.12 + Math.sqrt(city[2]) * 0.045;
    }
    const lat = anchor[0] + gauss() * sigma;
    const lng = anchor[1] + (gauss() * sigma) / Math.max(0.2, Math.cos((anchor[0] * Math.PI) / 180));
    arr.push([lat, lng, 1]);
  }
  return arr;
}
